"""preCICE participant: one half of the two-slab steady conjugate-heat problem,
solved with scikit-fem 1D P1 elements. Same analytic answer as the
fourc_kratos_cht pair: T_if = (TL*k1/L1 + TR*k2/L2)/(k1/L1 + k2/L2).

Usage:  python participant_slab.py <SlabA|SlabB>
  SlabA (Dirichlet side): [0, L1], k1; T=TL at x=0, T=T_if (read from preCICE,
        data "Interface-Temperature") at x=L1; writes the interface normal
        flux q = -k1*dT/dx (one-sided over the last element, exact for the
        linear steady profile) as data "Heat-Flux".
  SlabB (Neumann side): [L1, L1+L2], k2; incoming flux q (read, "Heat-Flux")
        applied as the natural boundary term at x=L1, T=TR at x=L1+L2;
        writes the interface temperature as "Interface-Temperature".

The coupling scheme (serial-implicit + Aitken, generated by
src/core/precice_config.generate_precice_config through run_precice_coupling)
iterates this Dirichlet-Neumann map inside one time window. Each participant
writes its converged interface value to result_<name>.json on finalize.

Run under the repo .venv python with LD_LIBRARY_PATH=/opt/precice/lib (both
provided by core.precice_config.run_precice_coupling).
"""
import json
import sys
from pathlib import Path

import numpy as np
import precice
from skfem import Basis, ElementLineP1, MeshLine, asm
from skfem.models.poisson import laplace

PARAMS = json.loads(Path("params.json").read_text())
L1, L2 = PARAMS["L1"], PARAMS["L2"]
k1, k2 = PARAMS["k1"], PARAMS["k2"]
TL, TR = PARAMS["TL"], PARAMS["TR"]
N = PARAMS["n_elements"]


def solve_slab_a(T_if: float) -> float:
    """Dirichlet-Dirichlet solve on [0, L1]; return outward (+x) flux at x=L1."""
    mesh = MeshLine(np.linspace(0.0, L1, N + 1))
    basis = Basis(mesh, ElementLineP1())
    K = (k1 * asm(laplace, basis)).toarray()
    x = basis.doflocs[0]
    i_left = int(np.argmin(np.abs(x - 0.0)))
    i_right = int(np.argmin(np.abs(x - L1)))
    T = np.zeros(basis.N)
    T[i_left], T[i_right] = TL, T_if
    free = [i for i in range(basis.N) if i not in (i_left, i_right)]
    T[free] = np.linalg.solve(K[np.ix_(free, free)], -(K @ T)[free])
    order = np.argsort(x)
    xs, Ts = x[order], T[order]
    dx = xs[-1] - xs[-2]
    return float(-k1 * (Ts[-1] - Ts[-2]) / dx)          # one-sided, exact for P1


def solve_slab_b(q_in: float) -> float:
    """Neumann-Dirichlet solve on [L1, L1+L2]; return temperature at x=L1."""
    mesh = MeshLine(np.linspace(L1, L1 + L2, N + 1))
    basis = Basis(mesh, ElementLineP1())
    K = (k2 * asm(laplace, basis)).toarray()
    x = basis.doflocs[0]
    i_left = int(np.argmin(np.abs(x - L1)))
    i_right = int(np.argmin(np.abs(x - (L1 + L2))))
    f = np.zeros(basis.N)
    f[i_left] = q_in                                    # natural BC: incoming flux
    T = np.zeros(basis.N)
    T[i_right] = TR
    free = [i for i in range(basis.N) if i != i_right]
    T[free] = np.linalg.solve(K[np.ix_(free, free)], (f - K @ T)[free])
    return float(T[i_left])


def main() -> None:
    name = sys.argv[1]
    assert name in ("SlabA", "SlabB")
    p = precice.Participant(name, "precice-config.xml", 0, 1)
    mesh_name = f"{name}-Mesh"
    vid = p.set_mesh_vertices(mesh_name, np.array([[L1, 0.0]]))
    p.initialize()

    last = {"value": None, "iterations": 0}
    while p.is_coupling_ongoing():
        if p.requires_writing_checkpoint():
            pass                                        # steady solve: stateless
        dt = p.get_max_time_step_size()
        if name == "SlabA":
            T_if = float(p.read_data(mesh_name, "Interface-Temperature", vid, dt)[0])
            q = solve_slab_a(T_if)
            p.write_data(mesh_name, "Heat-Flux", vid, np.array([q]))
            last["value"] = q
            print(f"SlabA: read T_if={T_if:.8f} -> wrote q={q:.8f}", flush=True)
        else:
            q = float(p.read_data(mesh_name, "Heat-Flux", vid, dt)[0])
            T_if = solve_slab_b(q)
            p.write_data(mesh_name, "Interface-Temperature", vid, np.array([T_if]))
            last["value"] = T_if
            print(f"SlabB: read q={q:.8f} -> wrote T_if={T_if:.8f}", flush=True)
        last["iterations"] += 1
        p.advance(dt)
        if p.requires_reading_checkpoint():
            pass                                        # steady solve: stateless
    p.finalize()

    out = {"participant": name, "iterations": last["iterations"],
           ("final_flux" if name == "SlabA" else "final_interface_temperature"):
               last["value"]}
    Path(f"result_{name}.json").write_text(json.dumps(out, indent=2))
    print(f"{name} finished after {last['iterations']} coupling iteration(s)",
          flush=True)


if __name__ == "__main__":
    main()
